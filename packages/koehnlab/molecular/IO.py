from enum import Enum
from typing import Dict, List, Optional, Sequence, Tuple

import re

from .Molecule import Molecule
from .Atom import Atom
from .Element import Element

import numpy as np


class FileFormat(Enum):
    XYZ = 0


def _readRawXYZ(path: str) -> Tuple[List[str], np.ndarray]:
    """Reads the given XYZ file and returns the (unparsed) first column of every atom line as well as the coordinates"""
    tokens: List[str] = []
    coordinates: List[List[float]] = []

    with open(path, "r") as inputFile:
        lines = inputFile.readlines()

        if len(lines) < 3:
            raise RuntimeError("Invalid XYZ file '%s'" % path)

        nAtoms = int(lines[0])

        # second line is only the comment, which we don't care about

        for i in range(nAtoms):
            if i + 2 >= len(lines):
                raise RuntimeError("Invalid XYZ file '%s': Too few atom lines" % path)

            components = lines[i + 2].split()

            if len(components) < 4:
                raise RuntimeError("Invalid line in XYZ file: '%s':%d" % (path, i + 2))

            tokens.append(components[0])
            coordinates.append(
                [float(components[1]), float(components[2]), float(components[3])]
            )

    assert len(tokens) == nAtoms

    return tokens, np.asarray(coordinates, dtype=float).reshape(nAtoms, 3)


def readMolecule(path: str, fmt: FileFormat = FileFormat.XYZ) -> Molecule:
    """Reads a molecule in the given format from the given path on the filesystem"""
    if fmt != FileFormat.XYZ:
        raise RuntimeError("Unsupported file format %s" % str(fmt))

    tokens, coordinates = _readRawXYZ(path)

    return Molecule(
        [
            Atom(element=Element[token], coordinates=coordinates[i])
            for i, token in enumerate(tokens)
        ]
    )


_LABEL_PATTERN = re.compile(r"^([A-Za-z]+)(\d+)$")


def readLabeledMolecule(
    path: str, fmt: FileFormat = FileFormat.XYZ
) -> Tuple[Molecule, List[str]]:
    """Reads a molecule from an XYZ file in which the element column may contain atom labels
    like "C1", "Cl2" or "H17" (an element symbol followed by a number) instead of plain element symbols.
    Returns the molecule as well as the label of every atom.

    If the file only contains plain element symbols, labels are generated by appending a per-element counter
    in the order of appearance (C1, C2, ..., H1, H2, ...). Mixing labeled and unlabeled atoms is an error,
    just like duplicate labels.
    """
    if fmt != FileFormat.XYZ:
        raise RuntimeError("Unsupported file format %s" % str(fmt))

    tokens, coordinates = _readRawXYZ(path)

    elements: List[Element] = []
    labeled: List[bool] = []

    for i, token in enumerate(tokens):
        match = _LABEL_PATTERN.match(token)
        symbol = match.group(1) if match else token
        try:
            elements.append(Element[symbol])
        except KeyError:
            raise RuntimeError(
                "Unknown element '%s' in XYZ file '%s':%d" % (symbol, path, i + 3)
            )
        labeled.append(match is not None)

    labels: List[str]
    if all(labeled):
        labels = list(tokens)
    elif not any(labeled):
        counters: Dict[Element, int] = {}
        labels = []
        for element in elements:
            counters[element] = counters.get(element, 0) + 1
            labels.append("%s%d" % (element.symbol(), counters[element]))
    else:
        raise RuntimeError(
            "XYZ file '%s' mixes labeled and unlabeled atoms" % path
        )

    if len(set(labels)) != len(labels):
        raise RuntimeError("XYZ file '%s' contains duplicate atom labels" % path)

    molecule = Molecule(
        [Atom(element=el, coordinates=coordinates[i]) for i, el in enumerate(elements)]
    )

    return molecule, labels


def writeMolecule(
    molecule: Molecule,
    path: str,
    fmt: FileFormat = FileFormat.XYZ,
    labels: Optional[Sequence[str]] = None,
) -> None:
    """Writes the given Molecule's geometry to a file at the given path and in the specified format.
    If labels are given, they are written instead of the plain element symbols (one label per atom)."""
    if fmt != FileFormat.XYZ:
        raise RuntimeError("Unsupported file format %s" % str(fmt))

    if labels is not None and len(labels) != len(molecule.atoms):
        raise ValueError("Expected one label per atom")

    with open(path, "w") as outputFile:
        outputFile.write("{}\n\n".format(len(molecule.atoms)))
        for i, currentAtom in enumerate(molecule.atoms):
            name = currentAtom.element.symbol() if labels is None else labels[i]
            outputFile.write(
                "{: <2s} {: 17.12f} {: 17.12f} {: 17.12f}\n".format(
                    name,
                    currentAtom.coordinates[0],
                    currentAtom.coordinates[1],
                    currentAtom.coordinates[2],
                )
            )
